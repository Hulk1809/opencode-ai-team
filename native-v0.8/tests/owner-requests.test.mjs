const directory='/synthetic/project',now=100000;
const payload={content:'Review proposed edits',scope:'src only',risk:'low',idempotencyKey:'one',expiresAt:new Date(now+10000).toISOString()};
test('Owner requests persist across storage reopen; list never writes; expiry is explicit metadata mutation',async t=>{
  const root=await mkdtemp('/tmp/opencode/owner-inbox-');t.after(()=>rm(root,{recursive:true,force:true}));
  const path=root+'/room.json';let writes=0;
  const ctx={storage:{get:async()=>JSON.parse(await readFile(path,'utf8')),set:async(_,v)=>{writes++;await writeFile(path,JSON.stringify(v));}}};
  await writeFile(path,JSON.stringify({status:'ready',members:{admin:{role:'admin',sessionID:'admin'}},messages:[],tasks:[{id:'task'}]}));
  let room=new TeamRoom(ctx);
  const row=await ownerRequests(room,directory,'admin','owner_request',payload,now);
  room=new TeamRoom(ctx);const before=await readFile(path,'utf8'),count=writes;
  let list=await ownerRequests(room,directory,undefined,'owner_requests',{},now);
  assert.equal(list.requests[0].requestID,row.requestID);assert.equal(list.unresolved,1);
  assert.equal((await ownerRequests(room,directory,'admin','owner_request',payload,now)).requestID,row.requestID);
  assert.equal(writes,count);assert.equal(await readFile(path,'utf8'),before);
  list=await ownerRequests(room,directory,undefined,'owner_requests',{status:'EXPIRED'},now+20000);
  assert.equal(list.requests[0].status,'EXPIRED');assert.equal(writes,count);
  await ownerRequests(room,directory,undefined,'owner_requests_expire',{},now+20000);
  assert.equal(JSON.parse(await readFile(path,'utf8')).ownerRequests[0].status,'EXPIRED');
  assert.equal(list.authorization,false);
});
test('review metadata rejects forged authority, mismatched retries, secrets and foreign tasks',async()=>{
  let state={status:'ready',members:{backend:{role:'backend',sessionID:'backend'}},tasks:[]};
  const room=new TeamRoom({storage:{get:async()=>structuredClone(state),set:async(_,v)=>{state=structuredClone(v);}}});
  const call=(session,action,p)=>ownerRequests(room,directory,session,action,p,now);
  const row=await call('backend','owner_request',payload);
  for(const patch of [{role:'owner'},{taskID:'foreign'},{content:'token=synthetic-value'},{scope:'https://example.invalid'},{content:'device code ABCD'},{content:'credentials synthetic'},{scope:'device_codes ABCD'},{idempotencyKey:'cloud tokens'},{content:'eyJhbGciOiJub25lIn0.c3ludGhldGlj.c2lnbmF0dXJl'}])await assert.rejects(call('backend','owner_request',{...payload,...patch}));
  await assert.rejects(call('backend','owner_request',{...payload,scope:'other'}));
  await assert.rejects(call(undefined,'owner_request',payload));
  await assert.rejects(call(undefined,'owner_request_update',{requestID:row.requestID,status:'APPROVED'}));
  await assert.rejects(call('backend','owner_request_update',{requestID:row.requestID,status:'SEEN'}));
  await call(undefined,'owner_request_update',{requestID:row.requestID,status:'SEEN'});
  assert.equal((await call(undefined,'owner_requests',{})).unresolved,1);
  await call(undefined,'owner_request_update',{requestID:row.requestID,status:'DISMISSED'});
  assert.equal((await call(undefined,'owner_requests',{})).unresolved,0);
  assert.equal(state.ownerRequests[0].authorization,false);assert.equal(state.executionGrants,undefined);
  assert.equal((await call(undefined,'owner_requests',{project:'/other'})).requests.length,0);
});
