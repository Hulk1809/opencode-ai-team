test('stable append-only pagination survives new requests, filters and readonly reload',async()=>{
  let state={status:'ready',members:{admin:{role:'admin',sessionID:'admin'}},tasks:[]},writes=0;
  const ctx={storage:{get:async()=>structuredClone(state),set:async(_,v)=>{writes++;state=structuredClone(v);}}};
  const create=i=>ownerRequests(new TeamRoom(ctx),directory,'admin','owner_request',{...payload,idempotencyKey:String(i)},now);
  for(let i=0;i<3;i++)await create(i);
  const list=p=>ownerRequests(new TeamRoom(ctx),directory,undefined,'owner_requests',p,now);
  const first=await list({limit:1});await create(3);const count=writes;
  const second=await list({limit:2,after:first.next,asOf:first.asOf,snapshot:first.snapshot});
  assert.deepEqual(second.requests.map(r=>r.sequence),[2,3]);assert.equal(second.next,null);
  assert.equal((await list({status:'DISMISSED'})).requests.length,0);assert.equal(writes,count);
  await assert.rejects(list({limit:0}));await assert.rejects(list({after:-1}));
  await assert.rejects(list({after:1,asOf:first.asOf}),/cursor/);
  const late=await ownerRequests(new TeamRoom(ctx),directory,undefined,'owner_requests',{after:first.next,asOf:first.asOf,snapshot:first.snapshot},now+20000);
  assert.equal(late.requests[0].status,'PENDING_REVIEW');
  await ownerRequests(new TeamRoom(ctx),directory,undefined,'owner_request_update',{requestID:first.requests[0].requestID,status:'SEEN'},now);
  await assert.rejects(list({after:first.next,asOf:first.asOf,snapshot:first.snapshot}),/restart pagination/);
});
