import test from 'node:test';
import assert from 'node:assert/strict';
import {ownerAdminSend,ownerAdminHistory,ownerTranscript,stableRows} from '../src/native-owner.mjs';
import {nativeCaller} from '../src/native-caller.mjs';
import {TeamRoom} from '../src/room.mjs';

test('native chat integration: bound Owner, peer queue, dedup and read-only reconnect',async()=>{
  const directory='/fixture',projectID='project-fixture',store=new Map(),admissions=new Map(),calls=[];
  const members=Object.fromEntries(['admin','backend','frontend','qa','devops'].map(role=>[role,{role,sessionID:`s-${role}`,directory}]));
  const sessions=Object.fromEntries(Object.values(members).map(m=>[m.sessionID,{id:m.sessionID,agent:m.role,projectID,metadata:{teamDirectory:directory},location:{directory}}]));
  const ctx={location:{directory,project:{id:projectID}},storage:{get:async k=>structuredClone(store.get(k)),set:async(k,v)=>store.set(k,structuredClone(v))},session:{get:async({sessionID})=>sessions[sessionID],context:async()=>[],prompt:async input=>{calls.push(input);if(!admissions.has(input.id))admissions.set(input.id,{id:input.id,type:'user',delivery:'queue'});return admissions.get(input.id)}}};
  const room=new TeamRoom(ctx);
  await room.write(directory,{directory,projectID,status:'ready',members,messages:[],tasks:[{id:'t',status:'working',dependencies:[]}]});
  const contract={},client={session:ctx.session,rpc:c=>{assert.equal(c,contract);return {snapshot:async({directory:d})=>room.snapshot(d)}}};
  const host={id:'owner-view',directory,location:{directory},project:{id:projectID},server:{id:'fixture-server',client,connected:true,compatible:true}};
  const attempt={id:`msg_${'a'.repeat(32)}`,text:'Owner request'};
  await ownerAdminSend(()=>host,contract,attempt);
  await ownerAdminSend(()=>host,contract,attempt);
  assert.equal(admissions.size,1);assert.equal(calls[0].sessionID,'s-admin');assert.equal(calls[0].delivery,'queue');
  sessions['s-admin'].projectID='foreign';await assert.rejects(ownerAdminSend(()=>host,contract,attempt),/BINDING_MISMATCH/);sessions['s-admin'].projectID=projectID;
  sessions['s-admin'].id='forged';await assert.rejects(ownerAdminSend(()=>host,contract,attempt),/BINDING_MISMATCH/);sessions['s-admin'].id='s-admin';
  const peer=async(source,to,text,key)=>{const caller=await nativeCaller(ctx,room,`s-${source}`);return room.sendAsSession(caller.directory,caller.sessionID,to,text,{taskID:'t',idempotencyKey:key})};
  const first=await peer('backend','frontend','Review UI','peer-1');
  assert.equal(await peer('backend','frontend','Review UI','peer-1'),first);
  await peer('qa','backend','Review evidence','peer-2');
  const waiting=await peer('backend','frontend','Next question','peer-3');
  const before=await room.snapshot(directory),count=calls.length;
  assert.equal(before.messages.find(m=>m.id===waiting).status,'waiting');
  assert.equal(calls.filter(c=>c.sessionID==='s-frontend').length,1);
  assert.ok(calls.some(c=>c.sessionID==='s-backend'));
  assert.ok(calls.every(c=>c.delivery==='queue'));
  const reconnected=new TeamRoom(ctx);
  assert.deepEqual(await reconnected.snapshot(directory),before);
  assert.deepEqual(await reconnected.snapshot(directory),before);
  assert.equal(calls.length,count);assert.equal(before.tasks[0].status,'working');
  const user={id:attempt.id,type:'user',text:attempt.text,metadata:calls[0].metadata,time:{created:1}};
  const answer={id:'answer',type:'assistant',agent:'admin',content:[{type:'text',text:'Admin reply'}],time:{created:2,completed:3},finish:'stop'};
  client.message={list:async({cursor})=>cursor?{data:[answer],cursor:{}}:{data:[user],cursor:{next:'page-2'}}};
  ctx.session.inbox={list:async()=>[{id:attempt.id,type:'user',payload:{text:attempt.text,metadata:calls[0].metadata},delivery:'queue',time:{created:1}}]};
  const projection=await ownerAdminHistory(()=>host,contract);
  assert.equal(projection.length,2);assert.equal(projection[0].status,'admitted');assert.equal(projection[1].status,'completed');assert.equal(projection[1].promptID,attempt.id);
  assert.deepEqual(await ownerAdminHistory(()=>host,contract),projection);assert.equal(calls.length,count);
  answer.finish='error';assert.equal((await ownerAdminHistory(()=>host,contract))[1].status,'failed');
  answer.finish=undefined;delete answer.time.completed;assert.equal((await ownerAdminHistory(()=>host,contract))[1].status,'running');
  client.message.list=async()=>({data:[user,{id:'other',type:'user',time:{created:2},text:'unrelated'},answer],cursor:{}});
  assert.equal((await ownerAdminHistory(()=>host,contract)).length,1);
  client.message.list=async()=>({data:[],cursor:{}});
  assert.equal((await ownerAdminHistory(()=>host,contract))[0].status,'queued');
  answer.time.completed=3;answer.finish='unknown';
  client.message.list=async()=>({data:[user,user,answer,answer],cursor:{}});
  const unknown=await ownerAdminHistory(()=>host,contract);assert.equal(unknown.length,2);assert.equal(unknown[1].status,'unknown');
  const second={...user,id:'second',text:'Second input'};
  const ambiguous=ownerTranscript([user,second,answer],[]);
  assert.equal(ambiguous.at(-1).correlation,'ambiguous-inputs');assert.equal(ambiguous.at(-1).promptID,undefined);
  const toolAnswer={...answer,content:[{type:'tool',id:'tool-call',name:'mcp_example',executed:true,state:{status:'completed',content:[{type:'text',text:'Tool result'},{type:'file',uri:'private-file'}]}}]};
  const tools=ownerTranscript([user,toolAnswer],[]).at(-1).tools;
  assert.equal(tools[0].result,'Tool result');assert.equal(tools[0].status,'completed');assert.equal(tools[0].executed,true);
  assert.equal(stableRows(projection,structuredClone(projection)),projection);
  const changed=structuredClone(projection);changed[1].status='running';assert.equal(stableRows(projection,changed)[0],projection[0]);
  const prompt=ctx.session.prompt;let timedOutCalls=0;
  ctx.session.prompt=async(_input,options)=>{assert.ok(options.signal instanceof AbortSignal);timedOutCalls++;throw new DOMException('fixture timeout','TimeoutError')};
  const uncertain={id:`msg_${'b'.repeat(32)}`,text:'Timeout request'};
  await assert.rejects(ownerAdminSend(()=>host,contract,uncertain),/fixture timeout/);
  assert.ok(uncertain.binding);assert.equal(timedOutCalls,1);
  await ownerAdminHistory(()=>host,contract);assert.equal(timedOutCalls,1);
  ctx.session.prompt=prompt;
  await assert.rejects(nativeCaller(ctx,room,'spoofed'));
  ctx.location.directory='/foreign';await assert.rejects(nativeCaller(ctx,room,'s-backend'),/LOCATION_UNAVAILABLE/);
});
