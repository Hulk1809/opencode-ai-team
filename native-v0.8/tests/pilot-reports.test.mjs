import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,symlinkSync} from 'node:fs';
import {join} from 'node:path';
import {reportBody,writeReport,readReport} from '../src/pilot-reports.mjs';
import {OfficialCoordinator} from '../src/official-coordinator.mjs';

test('real report persists, validates evidence and isolates project/team/task without path access',()=>{
  const directory=mkdtempSync('/tmp/opencode/reports-');
  const member={role:'worker-1',sessionID:'ses_worker'},state={projectID:'A',teamID:'team_A',members:[member],tasks:[{id:'task_1',assignee:'worker-1',text:'Deterministic fixture; no model execution'}],artifacts:[]};
  const input={taskID:'task_1',text:'Fixture generated by test, not proof of source edits.',files:['src/file.mjs'],commands:[{command:'node --version',exitCode:0,output:process.version}],diff:'Fixture only: no source change',remaining:'None in fixture',status:'completed'};
  const report=reportBody(input,state,member);writeReport(directory,report);writeReport(directory,report);
  const {content,...metadata}=report;state.artifacts.push(metadata);
  const restarted=JSON.parse(JSON.stringify(state));
  assert.equal(readReport(directory,restarted,'A',report.id).content,content);
  assert.equal(readFileSync(join(directory,'reports',report.storageRef),'utf8'),content);
  for(const changes of [{taskID:'other'},{files:['../secret']},{files:['/etc/passwd']},{commands:[]},{commands:[{command:'test',exitCode:1,output:'fail'}]},{diff:''}])assert.throws(()=>reportBody({...input,...changes},state,member));
  for(const id of ['../team.json','report_x',null])assert.throws(()=>readReport(directory,state,'A',id));
  assert.throws(()=>readReport(directory,state,'B',report.id));
  assert.throws(()=>readReport(directory,{...state,teamID:'other'},'A',report.id));
  assert.throws(()=>readReport(directory,{...state,tasks:[]},'A',report.id));
  writeFileSync(join(directory,'reports',report.storageRef),'tampered');
  assert.throws(()=>readReport(directory,state,'A',report.id),/INTEGRITY/);
  const unsafe=mkdtempSync('/tmp/opencode/reports-unsafe-');symlinkSync(directory,join(unsafe,'reports'));
  assert.throws(()=>writeReport(unsafe,report),/UNSAFE/);
});

test('coordinator report attachment is idempotent, caller-authorized, and never dispatches',async()=>{
  const directory=mkdtempSync('/tmp/opencode/report-coordinator-');
  const member={role:'worker-1',sessionID:'ses_worker',directory:'/fixture'},admin={role:'admin',sessionID:'ses_admin',directory:'/fixture'};
  const ctx={location:{project:{canonical:'/fixture',id:'A'}},options:{pilotStore:directory}};
  const coordinator=new OfficialCoordinator(ctx);
  coordinator.mutate(()=>({state:{status:'ready',projectID:'A',teamID:'team_A',members:[member,admin],tasks:[{id:'task_1',assignee:member.role,text:'Fixture'}],messages:[]}}));
  coordinator.caller=async context=>{assert.equal(context.sessionID,member.sessionID);return member;};
  const input={taskID:'task_1',text:'Fixture report',files:[],commands:[{command:'assert',exitCode:0,output:'pass'}],diff:'No source diff',remaining:'',status:'completed'};
  await assert.rejects(coordinator.execute('ack',{taskID:'task_1',status:'done'},{sessionID:member.sessionID}),/REPORT_REQUIRED/);
  const a=await coordinator.execute('report',input,{sessionID:member.sessionID});
  assert.deepEqual(await coordinator.execute('report',input,{sessionID:member.sessionID}),a);
  assert.equal(coordinator.read().messages.length,1);assert.equal(coordinator.read().artifacts.length,1);
  assert.equal(coordinator.read().tasks[0].status,undefined);
  assert.equal(coordinator.read().messages[0].artifactID,a.id);
  const reopened=new OfficialCoordinator(ctx);assert.equal(readReport(reopened.directory,reopened.read(),'A',a.id).content.includes('Fixture report'),true);
  await assert.rejects(coordinator.execute('report',input,{sessionID:'spoofed'}));
  await coordinator.execute('ack',{taskID:'task_1',status:'done'},{sessionID:member.sessionID});
  assert.equal(coordinator.read().tasks[0].status,'done');
  coordinator.caller=async()=>admin;
  const summary=await coordinator.execute('report',{...input,text:'Admin summary'},{sessionID:admin.sessionID});
  assert.equal(coordinator.read().messages[1].to,'owner');
  assert.equal(readReport(reopened.directory,reopened.read(),'A',summary.id).owner,'admin');
});
